// 等机会计分：每维在 24 题中出现 12 次；选中一次记 1 次。
// 原型权重由编辑定义；使用归一化向量的平方距离排序，不输出匹配概率。
window.matchArchive = function(answers) {
  const {questions,dimensions,people}=window.ARCHIVE;
  if(!Array.isArray(answers)||answers.length!==questions.length||answers.some(a=>!Number.isInteger(a)||a<0||a>3)) return null;
  const counts=dimensions.map(()=>0);
  answers.forEach((a,i)=>counts[questions[i].scores[a]]++);
  const ranking=people.map(person=>{
    const sum=person.weights.reduce((a,b)=>a+b,0);
    const distance=person.weights.reduce((total,w,i)=>total+(counts[i]/questions.length-w/sum)**2,0);
    return {person,distance};
  }).sort((a,b)=>a.distance-b.distance||a.person.id.localeCompare(b.person.id));
  const spread=Math.max(...counts)-Math.min(...counts);
  const tied=ranking.filter(r=>Math.abs(r.distance-ranking[0].distance)<1e-10).map(r=>r.person.id);
  const close=ranking[1].distance-ranking[0].distance<0.006;
  const positionCounts=[0,1,2,3].map(a=>answers.filter(v=>v===a).length);
  return {person:ranking[0].person,runner:ranking[1].person,counts,ranking,tied,close,diffuse:spread<=2,positionBias:Math.max(...positionCounts)>=20};
};
